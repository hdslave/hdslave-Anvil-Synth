"""Bake Anvil's SP-16 text sizes. Run with Python 3 and Pillow."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[2]
masks = []
sizes = []
for size in (13, 16, 22):
    font = ImageFont.truetype(root / "assets/fonts/Barlow-SemiBold.ttf", size)
    cap_height = -font.getbbox("H", anchor="ls")[1]
    glyphs = []
    for code in range(32, 127):
        char = chr(code)
        x, y, right, bottom = font.getbbox(char, anchor="ls")
        w, h = right - x, bottom - y
        glyphs.append((len(masks), x, cap_height + y, w, h, round(font.getlength(char))))
        if w and h:
            tile = Image.new("L", (w, h))
            ImageDraw.Draw(tile).text((-x, -y), char, font=font, anchor="ls", fill=255)
            pixels = [(v + 8) // 17 for v in tile.tobytes()] + [0]
            masks.extend((a << 4) | b for a, b in zip(pixels[::2], pixels[1::2]))
    sizes.append(glyphs)

out = [
    "// Generated by tools/ui_preview/sp16_font.py. Barlow SemiBold, SIL OFL 1.1.",
    "#pragma once", "#include <cstdint>", "namespace anvil::sp16::font {",
    "struct Glyph { uint16_t offset; int8_t x, y; uint8_t w, h, advance; };",
    "inline constexpr Glyph glyphs[][95] = {",
]
for glyphs in sizes:
    out.append("    {")
    out.extend("        {" + ", ".join(map(str, g)) + "}," for g in glyphs)
    out.append("    },")
out.extend(["};", "inline constexpr uint8_t masks[] = {"])
for i in range(0, len(masks), 24):
    out.append("    " + ", ".join(f"0x{v:02x}" for v in masks[i:i+24]) + ",")
out += ["};", "static_assert(sizeof(masks) < 65536);", "} // namespace anvil::sp16::font"]
(root / "src/ui/sp16_font.h").write_text("\n".join(out) + "\n")
